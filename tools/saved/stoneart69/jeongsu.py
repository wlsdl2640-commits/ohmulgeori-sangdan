def orb_pal(c):
    c = hx(c); return [lt(c, .62), lt(c, .28), c, dk(c, .3), dk(c, .55)]


def mount(s, kind, lv):
    """받침: 구슬 가운데 (cx, cy)와 반지름을 돌려준다"""
    if kind == 'weapon':   # 비스듬한 칼날 판 (왼쪽 아래 → 오른쪽 위), 붉은 쇠
        s.fill(lens(3.2, 17.0, 17.0, 3.0, 3.3 + 0.25 * lv), (214, 218, 226), (162, 168, 182), (98, 104, 122))
        s.fill(cap(3.0, 17.2, 5.6, 14.6, 1.4), (200, 90, 70), (150, 52, 44), (96, 30, 30))   # 붉은 자루 끝
        return 10.0, 10.0
    if kind == 'armor':    # 방패 판 (강철) — 위는 곧고 아래는 뾰족
        sh = P([(4.2, 3.6), (15.8, 3.6), (15.8, 10.4), (13.8, 14.6), (10, 17.6), (6.2, 14.6), (4.2, 10.4)])
        s.fill(sh, (200, 210, 226), (146, 158, 180), (90, 100, 124))
        rim = rast(sh) - rast(P([(5.4, 4.8), (14.6, 4.8), (14.6, 10.2), (12.8, 13.9), (10, 16.2), (7.2, 13.9), (5.4, 10.2)]))
        for q in rim: s.px[q] = mix(s.px[q], (232, 236, 244), 0.35) if q[0] + q[1] < 21 else mix(s.px[q], (60, 66, 86), 0.4)
        return 10.0, 9.6
    # 장식용: 금 고리 + 위 고리 (펜던트)
    r = (3.4, 4.0, 4.6, 4.8)[lv] + 1.4
    ring = lambda x, y: (x - 10) ** 2 + (y - 11) ** 2 <= r * r and (x - 10) ** 2 + (y - 11) ** 2 >= (r - 1.5) ** 2
    s.fill(ring, (255, 236, 150), (222, 176, 70), (150, 108, 34))
    s.fill(lambda x, y: (x - 10) ** 2 + (y - (11 - r - 0.9)) ** 2 <= 2.1 ** 2 and (x - 10) ** 2 + (y - (11 - r - 0.9)) ** 2 >= 1.0 ** 2, (255, 236, 150), (222, 176, 70), (150, 108, 34))
    return 10.0, 11.0


def essence(kind, col, sym, lv):
    s = Ic()
    cx, cy = mount(s, kind, lv)
    r = (2.4, 3.1, 3.7, 3.9)[lv]
    pal = orb_pal(col)
    M = cabochon(s, C(cx, cy, r), pal)
    if lv >= 1:
        G = SYM[sym]; ox = round(cx - 2.5); oy = round(cy - 2.5)
        if lv == 1:   # 중급은 무늬를 흐리게 (가운데 3×3만)
            G = [row[1:4] for row in G[1:4]]; ox += 1; oy += 1
        light = mix(pal[0], (255, 255, 255), 0.55); dark = pal[4]
        for j, row in enumerate(G):
            for i, ch in enumerate(row):
                q = (ox + i, oy + j)
                if ch == '#' and q in M: s.px[q] = light
                elif ch == 'o' and q in M: s.px[q] = dark
    s.done()
    if lv == 3: top(s, hx(col), n=6, rot=0.2, glints=((16, 2),))
    elif lv == 2: glint(s, 16, 3, hx(col))
    return s.px


