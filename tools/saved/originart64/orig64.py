def bez(p0, p1, p2, t):
    a = (1 - t) ** 2; b = 2 * (1 - t) * t; c = t * t
    return (a * p0[0] + b * p1[0] + c * p2[0], a * p0[1] + b * p1[1] + c * p2[1])


def horn_mask(p0, p1, p2, r0, r1, n=48):
    """굽은 뿔: 베지어 곡선을 따라 굵기가 줄어드는 원들 — 칸마다 (곡선 위치 t)를 함께 준다"""
    pts = [(bez(p0, p1, p2, i / n), r0 + (r1 - r0) * (i / n), i / n) for i in range(n + 1)]
    out = {}
    for y in range(H):
        for x in range(W):
            cx, cy = x + .5, y + .5
            best = None
            for (q, r, t) in pts:
                d = math.hypot(cx - q[0], cy - q[1]) - r
                if d <= 0 and (best is None or d < best[0]): best = (d, t)
            if best: out[(x, y)] = best[1]
    return out


def shade_t(s, M, colfn):
    """곡선 위치 t로 색을 고르고 왼쪽 위 · 오른쪽 아래 가장자리를 밝게 · 어둡게"""
    for (x, y), t in M.items():
        c = colfn(t)
        tl = (x - 1, y) not in M or (x, y - 1) not in M; br = (x + 1, y) not in M or (x, y + 1) not in M
        s.px[(x, y)] = lt(c, .22) if tl and not br else dk(c, .3) if br and not tl else c
    s.O |= set(M)


