def ore(rock, rockc, crystals, lf, df, flecks, fc):
    s = Ic()
    Rm = s.fill(P(rock), *rockc)
    s.put(flecks, fc, Rm)
    for (cx, cy, ang, L, w) in crystals:
        pts, (a, b) = prism(cx, cy, ang, L, w, w)
        s.facets(P(pts), [(side(*a, *b), *df), (None, *lf)])
    return s


