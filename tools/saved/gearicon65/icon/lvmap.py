"""장비 단계 레벨 (11-10 21:31 사용자): 2차 전직 Lv50 · 3차 Lv100(각성 · 용사 삭제) · 4차 예정.
2차 직업부터 쓰는 장비는 전직 레벨부터 10레벨마다 16단계 — Lv50 · 60 … 200 (레벨 상한이 오를 것을 미리 넣어 둠).
1차부터 쓰는 장비(장검 · 스태프 · 단검 · 암기 · 라운드 실드 · 마법 두루마리)는 Lv1 · 10 … 150 그대로."""
JOB_LV = {1: 1, 2: 50, 3: 100, 4: 150}
def from_job(G, tier=2):
    """시안 레벨(1 · 10 … 150)을 tier차 전직 레벨부터로 옮긴다: k번째 → JOB_LV[tier] + 10k"""
    lv0 = JOB_LV[tier]
    for d in G:
        if d.get('_lv1') is None: d['_lv1'] = d['lv']
        k = 0 if d['_lv1'] == 1 else d['_lv1'] // 10
        d['lv'] = lv0 + 10 * k
