def Y(v): return v + OY


def legs(c, xf, xn, top, w, far='c', near='C', foot=2.6, knee=None):
    """먼 다리(그늘) · 가까운 다리 + 앞으로 내민 발"""
    for (x, ch, dx) in ((xf, far, -0.4), (xn, near, 0.4)):
        c.fill(rbox(x - w / 2, Y(top), x + w / 2, Y(30.4), 0.6), ch)
        c.fill(rbox(x - w / 2 - 0.4, Y(29.8), x + w / 2 + foot, Y(31.6), 0.5), ch)
        if knee: c.fill(rbox(x - w / 2 - 0.2, Y(knee), x + w / 2 + 0.4, Y(knee + 1.6), 0.6), ch)


