def wing(c, root, wrist, tips, sec, base, lite, dark, skip=(), jag=False, short=()):
    prim, secs = wing_feathers(root, wrist, tips, sec)
    keep = [f for i, f in enumerate(prim) if (len(prim) - 1 - i) not in skip]
    keep = [(a, b, (t[0] + (a[0] - t[0]) * 0.35, t[1] + (a[1] - t[1]) * 0.35) if (len(prim) - 1 - i) in short else t, w) for i, (a, b, t, w) in enumerate(keep)]
    layer(c, secs, base, lite, dark, jag); layer(c, keep, base, lite, dark, jag)
    c.fill(path([root, wrist], 1.3, 1.0), base); c.only(thin(root, wrist), lite, base)


def face_r(c, x, y, eye='e', skin='S', sk2='s'):
    """오른쪽을 보는 얼굴 (x, y) = 얼굴 가운데"""
    c.fill(ell(x, y, 3.3, 3.5), skin); c.only(ell(x - 1.0, y + 1.6, 2.6, 1.4), sk2, skin)
    c.fill(box(x + 0.4, y, x + 1.2, y), eye); c.fill(box(x + 2.4, y, x + 2.8, y), eye)


def robe(c, top, hem_y, x0, x1, ch, rag=True):
    pts = [(x0 + 3.0, top), (x1 - 1.0, top), (x1 + 0.6, top + 6.0), (x1 + 2.4, hem_y), (x0 - 1.2, hem_y), (x0 + 1.4, top + 6.0)]
    cells = poly(pts)
    if rag:
        for i, xx in enumerate(range(int(x0 - 1), int(x1 + 3))):
            if i % 3 == 1: cells -= {(xx, int(hem_y) - 1), (xx, int(hem_y) - 2)}
            if i % 3 == 2: cells -= {(xx, int(hem_y) - 1)}
    c.fill(cells, ch); return cells


