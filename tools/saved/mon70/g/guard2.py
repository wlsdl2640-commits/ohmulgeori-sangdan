def facet(c, pts, ch='C', lite='Q', dark='c'):
    P = poly(pts); c.fill(P, ch)
    cx = sum(p[0] for p in pts) / len(pts); cy = sum(p[1] for p in pts) / len(pts)
    for (x, y) in P:
        if y < cy - 0.6 and x < cx + 0.6: c.set(x, y, lite)
        elif y > cy + 0.8: c.set(x, y, dark)


