def crystal(c, b, t, w):
    (bx, by), (tx, ty) = b, t; L = math.hypot(tx - bx, ty - by); ux, uy = (tx - bx) / L, (ty - by) / L; nx, ny = -uy * w, ux * w
    cs = poly([(bx + nx, by + ny), (bx + ux * L * 0.72 + nx, by + uy * L * 0.72 + ny), (tx, ty), (bx + ux * L * 0.72 - nx, by + uy * L * 0.72 - ny), (bx - nx, by - ny)])
    c.fill(cs, 'X'); c.only(thin((bx + nx * 0.3, by + ny * 0.3), (bx + ux * L * 0.8, by + uy * L * 0.8)), 'x', 'X'); c.only(thin((bx - nx * 0.6, by - ny * 0.6), (bx + ux * L * 0.7 - nx * 0.6, by + uy * L * 0.7 - ny * 0.6)), 'z', 'X')


def stump():
    c = Cv(34, 40)
    roots(c)
    c.fill(path([(9.4, 14.0), (6.6, 19.0), (6.4, 23.0)], 2.0, 1.6), 'c')
    c.fill(rbox(8.6, 8.0, 20.6, 27.4, 2.6), 'C'); blunt(c.g, 'C', 'Q', 'c', bottom=1, side=0)                               # 굵은 그루터기 몸
    c.fill(ell(14.6, 8.4, 5.6, 1.4), 'Q'); c.only(ell(14.6, 8.4, 3.0, 0.7), 'c', 'Q')                                       # 잘린 윗면 나이테
    for (b, t, w) in (((11.0, 8.4), (8.0, 1.0), 1.3), ((14.0, 8.0), (14.6, -0.6), 1.5), ((17.6, 8.6), (21.6, 2.6), 1.2), ((19.6, 12.0), (24.4, 8.4), 1.0), ((9.0, 12.0), (4.6, 8.0), 1.0)):
        crystal(c, b, t, w)                                                                                                  # 솟은 연푸른 수정 가지
    for (x, y) in ((8.0, 0.4), (14.6, -1.2), (21.8, 2.0), (24.8, 7.8), (4.2, 7.4)): flower(c, x - 0.5, y - 0.5)               # 수정 끝 별꽃
    c.fill(box(15.4, 14.4, 16.2, 15.0), 'E'); c.fill(box(17.6, 14.4, 18.0, 15.0), 'E'); c.fill(thins([(15.0, 13.4), (18.4, 13.2)]), 'd')   # 눈
    c.only(ell(12.0, 22.0, 3.4, 2.2) | ell(18.4, 25.6, 2.6, 1.6) | ell(10.6, 9.6, 2.0, 1.0), 'A', 'CQc')                    # 이끼
    return c


