PC = {'C': '#a8b8d8', 'Q': '#dce6f8', 'c': '#6a7aa0', 'U': '#1e2a6a', 'u': '#121a48', 'Y': '#ffe070', 'y': '#fff8d0', 'E': '#3a8ae8', 'k': '#141a2a',
      'P': '#8ac8ff', 'p': '#ffffff', 'G': '#e8c050'}


def comet():
    c = Cv(34, 40)
    body(c)
    tail = [(14.6, 2.6), (11.0, 2.2), (7.0, 3.0), (3.6, 4.6), (1.0, 6.4)]
    c.fill(path(tail, 2.4, 0.8), 'P'); c.only(path(tail[:3], 1.0), 'y', 'P'); c.fill(ell(15.2, 2.6, 1.8, 1.6), 'p')               # 혜성 꼬리 깃 (뒤로 길게 · 아래로 처지지 않음)
    blunt(c.g, 'C', 'Q', 'c', bottom=1, side=0)
    visor(c, 'E')
    c.fill(ell(9.4, 17.2, 4.0, 4.4), 'C'); blunt(c.g, 'C', 'Q', 'c', bottom=1, side=1)                                      # 먼 팔 둥근 방패
    c.fill(star5(9.6, 17.4, 2.6, 1.1), 'Y'); c.fill(thins([(10.6, 11.0), (18.8, 11.0)]), 'G')                              # 다섯 꼭지 별 · 금테
    return c


B.add('constellation_c', 'C 혜성 깃 기사', '밝은 은청색 갑주와 금테 · 짙은 남빛 망토 · 둥근 투구의 가로 틈(파란 눈) · 투구에서 길게 흐르는 혜성 꼬리 깃(머리는 흰 빛) · 먼 팔의 둥근 방패에 노란 다섯 꼭지 별 · 긴 창',
      comet(), PC, [19, 12], 15, 20, arm=['C', 'c'], hand='C', idle={'h': [2, 3], 'a': -70})
B.dump()
