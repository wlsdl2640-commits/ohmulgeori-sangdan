"""성좌 기사 (constellation · 별의 정원 · 인간 · 강철 · 맞히면 출혈) 시안 — 사람꼴 · 창 · ms 1.2 · g2 없음
A 밤하늘 갑주 기사: 남빛 판금에 금빛 별과 가는 별자리 줄 · 가로 틈 투구(하늘빛 눈) · 투구에서 뒤로 흐르는 별빛 깃 · 별무늬 남빛 망토
B 별자리 몸 기사: 먹빛 은 갑주 조각 사이로 보이는 별 가득한 밤하늘 몸 · 가슴에 별자리 · 별빛 두 눈의 투구
C 혜성 깃 기사: 은청색 갑주 · 짙은 남빛 망토 · 투구에서 길게 흐르는 혜성 꼬리 깃 · 먼 팔의 둥근 방패에 다섯 꼭지 별
피한 것: 투구 틈의 세로 콧대(십자) · 짐승 꼴 화려한 갑옷(유명한 별자리 전사) · 날개 투구 · 후광"""
from kit import *

ACT = {'atk': ['thrust', 'side'], 'skl': ['pjump'], 'tk': 1.1,
       'fx': {'atk': {'pal': 'star', 'hit': 'pierce'}, 'skl': {'pal': 'star', 'hit': 'star', 'big': 1, 'after': 'motes'}}}
B = Batch('knight1', 'constellation', ACT, 'stargarden', show=[['thrust', 4], ['pjump', 5]], ms=1.2, wpn='lance')


def star5(cx, cy, R, r, rot=-90):
    return poly([(cx + math.cos(math.radians(rot + k * 36)) * (R if k % 2 == 0 else r), cy + math.sin(math.radians(rot + k * 36)) * (R if k % 2 == 0 else r)) for k in range(10)])


def body(c, arm='c', plate='C', cape='U'):
    c.fill(poly([(9.0, 11.0), (13.0, 11.0), (12.0, 30.0), (6.0, 30.6), (5.0, 26.0)]), cape)                                 # 등 뒤 망토
    c.fill(rbox(10.4, 21.4, 13.6, 30.2, 0.6), 'c'); c.fill(rbox(9.6, 29.4, 15.0, 31.0, 0.5), 'c')                          # 먼 다리
    c.fill(rbox(15.2, 21.4, 18.4, 30.2, 0.6), plate); c.fill(rbox(14.6, 29.4, 20.6, 31.0, 0.5), plate)                     # 가까운 다리
    c.fill(path([(10.6, 12.6), (9.0, 17.6)], 1.7, 1.5), arm)                                                                 # 먼 팔
    c.fill(poly([(10.0, 10.6), (19.4, 10.6), (19.8, 14.0), (18.6, 20.0), (11.0, 20.0), (9.8, 14.0)]), plate)                # 가슴 판금
    c.fill(poly([(10.4, 19.4), (18.6, 19.4), (19.6, 23.4), (9.6, 23.4)]), plate)                                            # 허리 자락
    c.fill(ell(18.6, 11.6, 2.8, 2.0), plate); c.fill(ell(10.6, 11.6, 2.2, 1.8), 'c')                                       # 어깨받이
    c.fill(rbox(11.6, 2.6, 18.4, 9.8, 2.4), plate)                                                                           # 둥근 투구
    c.fill(rbox(12.6, 9.2, 17.6, 10.8, 0.4), 'c')


def visor(c, eye='E'):
    c.fill(box(14.4, 5.6, 18.4, 6.6), 'k'); c.fill(box(15.4, 5.8, 16.2, 6.4), eye); c.fill(box(17.4, 5.8, 18.0, 6.4), eye)


# ── A 밤하늘 갑주 기사 ─────────────────────────────
PA = {'C': '#2a3a7a', 'Q': '#4a5eae', 'c': '#18224a', 'U': '#1e2858', 'u': '#121838', 'Y': '#ffe070', 'y': '#b8a050', 'E': '#9ae8ff', 'k': '#0a0e1e',
      'P': '#9ad0ff', 'p': '#e8f8ff', 'L': '#fffbe0'}


def nightsky():
    c = Cv(32, 40)
    body(c)
    plume = [(13.6, 3.0), (10.6, 2.4), (8.0, 3.6), (6.6, 6.0)]                                                              # 투구 꼭대기에서 뒤로 늘어진 별빛 술
    c.fill(path(plume, 2.0, 1.2), 'P'); c.only(path(plume[:2], 0.7), 'p', 'P')
    for (x, y) in ((9.0, 3.0), (7.0, 5.6)): c.set(x, y, 'L')
    blunt(c.g, 'C', 'Q', 'c', bottom=1, side=0)
    visor(c)
    stars = [(12.0, 13.4), (14.8, 12.6), (17.2, 14.0), (16.0, 16.8), (12.8, 17.0), (12.0, 13.4)]
    for a, b in zip(stars, stars[1:]): c.only(thin(a, b), 'y', 'CQc')                                                        # 가는 별자리 줄 (닫힌 다섯 별 고리)
    for (x, y) in stars + [(15.0, 21.6), (17.6, 22.6)]: c.set(x, y, 'Y')
    for (x, y) in ((8.0, 18.0), (6.6, 24.0), (9.6, 27.0)): c.set(x, y, 'L')                                                 # 망토 별
    return c


B.add('constellation', 'A 밤하늘 갑주 기사', '남빛 판금 위 금빛 별과 가는 별자리 줄(닫힌 별 고리) · 둥근 투구의 가로 틈 하나(하늘빛 두 눈) · 투구 꼭대기에서 뒤로 늘어진 별빛 술 · 별이 박힌 남빛 망토 · 긴 창',
      nightsky(), PA, [19, 12], 15, 20, arm=['C', 'c'], hand='C', idle={'h': [2, 3], 'a': -70})


# ── B 별자리 몸 기사 ─────────────────────────────
PB = {'C': '#5a5e74', 'Q': '#8a8ea6', 'c': '#363a4c', 'U': '#20203a', 'u': '#14142a', 'V': '#141238', 'L': '#fff6c0', 'l': '#9ab4ff', 'E': '#fff0a0', 'k': '#08081a'}


def void():
    c = Cv(32, 40)
    body(c, cape='U')
    blunt(c.g, 'C', 'Q', 'c', bottom=1, side=0)
    gap = poly([(11.6, 13.0), (17.8, 12.8), (17.0, 19.6), (12.4, 19.6)]) | rbox(15.6, 23.6, 17.8, 28.0, 0.4) | rbox(13.0, 3.6, 17.0, 8.4, 1.6)
    c.only(gap, 'V', 'CQc')                                                                                                   # 갑주 조각 사이 밤하늘 몸
    pts = [(12.6, 14.0), (14.8, 15.4), (16.8, 14.0), (15.6, 17.8), (13.4, 18.6)]
    for a, b in zip(pts, pts[1:]): c.only(thin(a, b), 'l', 'V')                                                              # 가슴 별자리
    for (x, y) in pts + [(16.4, 25.0), (14.0, 4.6)]: c.set(x, y, 'L')
    c.fill(box(15.4, 5.8, 16.2, 6.4), 'E'); c.fill(box(17.4, 5.8, 18.0, 6.4), 'E')                                         # 별빛 두 눈
    c.fill(rbox(16.6, 4.4, 18.6, 8.6, 0.8), 'C'); c.fill(box(17.0, 5.8, 17.6, 6.4), 'E')                                    # 얼굴 가리개 조각 (눈 하나 보임)
    return c


B.add('constellation_b', 'B 별자리 몸 기사', '먹빛 은 갑주 조각(투구 · 어깨 · 가슴 테 · 다리) 사이로 보이는 별 가득한 밤하늘 몸 · 가슴에 이어진 별자리 · 투구 속 별빛 눈 · 짙은 망토 · 긴 창',
      void(), PB, [19, 12], 15, 20, arm=['C', 'c'], hand='C', idle={'h': [2, 3], 'a': -70})


