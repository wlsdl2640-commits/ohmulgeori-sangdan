def dragon(c, body='C', lite='Q', dark='c', belly='P', horn='O', head_y=10.0):
    """옆모습 용 몸 (날개 빼고): 다리 넷 · 몸통 · 목 · 머리 · 꼬리. 돌려주는 값: 등 날개 뿌리 · 머리 자리"""
    # 꼬리 (먼저)
    c.fill(path([(16.0, 27.0), (10.0, 30.0), (5.0, 32.0), (2.0, 29.0), (3.0, 24.0)], 2.6, 0.8), body)
    # 먼 다리 (굽은 뒷다리 · 앞다리)
    c.fill(path([(18.0, 28.0), (14.6, 34.0), (17.0, 41.0)], 2.6, 1.8), dark); c.fill(ell(18.0, 41.6, 2.4, 1.0), dark)
    c.fill(path([(31.0, 29.0), (34.0, 34.0), (32.0, 41.0)], 2.4, 1.8), dark); c.fill(ell(33.0, 41.6, 2.4, 1.0), dark)
    # 몸통 · 굵은 목 · 큰 머리
    c.fill(ell(25.6, 25.6, 12.4, 8.2), body)
    c.fill(path([(32.0, 24.0), (36.0, 18.6), (38.6, 14.6)], 5.0, 3.8), body)
    c.fill(ell(41.0, head_y + 1.0, 5.0, 4.2), body)
    c.fill(poly([(43.0, head_y - 1.8), (51.6, head_y + 1.4), (51.6, head_y + 3.6), (43.0, head_y + 4.6)]), body)         # 주둥이
    c.fill(poly([(42.0, head_y + 3.8), (50.0, head_y + 4.4), (48.6, head_y + 6.2), (41.6, head_y + 5.6)]), body)         # 아래턱
    # 가까운 다리 (굽은 뒷다리 · 앞다리, 굵게)
    c.fill(path([(21.0, 28.0), (17.0, 34.6), (20.6, 42.0)], 3.2, 2.0), body); c.fill(ell(22.0, 42.6, 2.9, 1.1), body)
    c.fill(path([(34.0, 28.0), (37.6, 34.0), (35.6, 42.0)], 3.0, 2.0), body); c.fill(ell(37.0, 42.6, 2.9, 1.1), body)
    blunt(c.g, body, lite, dark, bottom=1, side=0)
    bl = {(x, y) for (x, y) in ell(27.0, 30.6, 10.6, 3.0) if c.get(x, y) in (body, lite, dark) and y > 28} | {(x, y) for (x, y) in path([(35.0, 26.0), (39.4, 19.6), (42.0, 15.6)], 1.6) if c.get(x, y) in (body, lite, dark)}
    c.fill(bl, belly)                                                                                                         # 배 · 목 아래 비늘
    for k in range(5): c.only(thin((19.0 + k * 4.0, 29.0), (20.0 + k * 4.0, 32.4)), dark, belly)
    c.fill(thin((44.0, head_y + 3.8), (51.0, head_y + 3.8)), 'k')                                                            # 입 줄
    for (x, y) in ((49.6, head_y + 4.4), (47.0, head_y + 4.4)): c.set(x, y, 'w')                                             # 이빨
    c.set(50.8, head_y + 1.8, 'k')                                                                                            # 콧구멍
    for (x, y) in ((23.0, 43.0), (24.8, 43.0), (38.0, 43.0), (39.8, 43.0)): c.set(x, y, 'w')                                 # 발톱
    return (25.0, 19.6), (42.0, head_y)


