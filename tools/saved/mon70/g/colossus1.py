GY = 51


def legs(c, xf, xn, top, w, far='c', near='C', foot=3.4):
    for (x, ch) in ((xf, far), (xn, near)):
        c.fill(rbox(x - w / 2, top, x + w / 2, GY - 1.6, 0.8), ch)
        c.fill(rbox(x - w / 2 - 0.6, GY - 2.4, x + w / 2 + foot, GY, 0.6), ch)


def far_arm(c, ch='c', fist='c'):
    c.fill(path([(13.4, 20.4), (10.6, 27.4), (10.2, 33.4)], 3.0, 2.7), ch)
    c.fill(rbox(6.6, 32.4, 14.0, 39.0, 1.6), fist)


