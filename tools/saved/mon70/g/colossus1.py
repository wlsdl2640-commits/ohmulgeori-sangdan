def colm(c, x0, x1, y0, y1, ch='C', flute='d'):
    c.fill(box(x0, y0, x1, y1), ch); c.fill(box(x0 - 0.6, y0 - 1.0, x1 + 0.6, y0 - 0.2), ch); c.fill(box(x0 - 0.6, y1 + 0.2, x1 + 0.6, y1 + 1.0), ch)
    for x in range(int(x0) + 1, int(x1), 2): c.only(box(x, y0 + 0.4, x, y1 - 0.4), flute, ch + 'QcC')


