# ───────── 13. 깃털 (공격 속도 · 회피) ─────────
def feather(s, x0, y0, x1, y1, w, cols, shaft, bars=None):
    vane = prof(x0, y0, x1, y1, lambda u: 0 if u < 0.16 else (w * math.sin(math.pi * min(1, (u - 0.16) / 0.84)) ** 0.55 * (0.8 if u < .5 else 1), w * math.sin(math.pi * min(1, (u - 0.16) / 0.84)) ** 0.55))
    L = math.hypot(x1 - x0, y1 - y0); ux, uy = (x1 - x0) / L, (y1 - y0) / L
    def col(x, y, M):
        dx, dy = x + .5 - x0, y + .5 - y0; u = (dx * ux + dy * uy); v = -dx * uy + dy * ux
        tl = (x - 1, y) not in M or (x, y - 1) not in M; br = (x + 1, y) not in M or (x, y + 1) not in M
        c = bars[int((u + abs(v) * 0.9) // 1.6) % len(bars)] if bars else (cols[1] if v > 0 else cols[0])
        return lt(c, .18) if tl and not br else dk(c, .22) if br and not tl else c
    M = s.paint(vane, col)
    s.line([(x0, y0), (x1, y1)], shaft, None, ol=True)
    return M


