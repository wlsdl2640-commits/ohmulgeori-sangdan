def glint(s, x, y, c):     # 빛 한 점: 밝은 칸 + 대각 흐린 칸 둘 (／)
    if not s.free((x, y)): return
    s.px[(x, y)] = (255, 252, 236)
    for (dx, dy), t in (((-1, 1), .15), ((1, -1), .45)):
        q = (x + dx, y + dy)
        if 0 <= q[0] < W and 0 <= q[1] < H and q not in s.px: s.px[q] = lt(c, t) if t < .3 else mix(c, (30, 36, 52), t)


def halo(s, c, t=.64):     # 테 바깥 한 칸을 그 룬 색으로 은은하게
    occ = set(s.px); out = {}
    for (x, y) in occ:
        for dx in (-1, 0, 1):
            for dy in (-1, 0, 1):
                q = (x + dx, y + dy)
                if q not in occ and 0 <= q[0] < W and 0 <= q[1] < H: out[q] = mix(c, (30, 36, 52), t)
    s.px.update(out)


def top(s, c, n=5, rot=0.4, glints=((16, 2),)):   # 최상급: 은은한 빛 + 기운 점 + 빛 한 점
    halo(s, c)
    for (x, y) in glints: glint(s, x, y, c)
    s.aura(lt(c, .2), mix(c, (30, 36, 52), .35), n=n, rot=rot, dist=2)


