    nm, rows, off = ALTS[k][i]
    R.SHAPES[vk] = R.SHAPES[k]; R.GLYPH[vk] = rows; R.GOFF[vk] = off
    R.GLYPH_FN.pop(vk, None)
    return X.make_top(vk, COL[k])
