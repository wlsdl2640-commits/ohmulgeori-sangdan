def put(s, spec, keep=None, ch_map=None):
    ox, oy, rows = spec
    for j, r in enumerate(rows):
        for i, ch in enumerate(r):
            if ch == '.': continue
            p = (ox + i, oy + j)
            if keep is None or p in keep: s.put(p[0], p[1], (ch_map or {}).get(ch, ch))
