# ── 벡터 모양 → 칸 (다각형 · 타원을 돌리고 키워서 16×20 판에 찍는다) ──
def ell(cx, cy, rx, ry, n=20, rot=0.0):
    c, s = math.cos(rot), math.sin(rot)
    return [(cx + rx * math.cos(t) * c - ry * math.sin(t) * s, cy + rx * math.cos(t) * s + ry * math.sin(t) * c) for t in (2 * math.pi * i / n for i in range(n))]
def xf(pts, s=1.0, rot=0.0, dx=0.0, dy=0.0, cx=0.0, cy=0.0, mirror=False):
    c, sn = math.cos(math.radians(rot)), math.sin(math.radians(rot)); out = []
    for (x, y) in pts:
        x, y = x - cx, y - cy
        if mirror: x = -x
        x, y = x * s, y * s
        out.append((x * c - y * sn + cx + dx, x * sn + y * c + cy + dy))
    return out
def raster(parts, **t):
    """parts = [(글자, 점들) …] 뒤에 오는 것이 위에 칠해진다. 점 하나짜리 ('k', [(x, y)])는 그 칸 하나."""
    cm = {}
    for ch, pts in parts:
        if len(pts) == 1:
            (x, y), = xf(pts, **t); cm[(int(math.floor(x)), int(math.floor(y)))] = ch; continue
        for xy in poly_cells(xf(pts, **t), ch): cm[xy] = ch
    return cm
