def sheet(out, items=GEAR, cols=2):
    from PIL import Image, ImageDraw, ImageFont
    f = ImageFont.truetype('/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc', 14, index=2)
    fb = ImageFont.truetype('/usr/share/fonts/opentype/noto/NotoSansCJK-Bold.ttc', 17, index=2)
    Z = 4; TW = W * Z + 8; GW = 4 * (TW + 4) + 110; RH = H * Z + 14
    rows_n = (len(items) + cols - 1) // cols
    sh = Image.new('RGB', (cols * GW + 20, rows_n * RH + 74), (21, 23, 28)); d = ImageDraw.Draw(sh)
    d.text((10, 10), '장비 그림 새로 그리기 시안 · 한 줄 = 견습·숲지기 / 강철·폭풍 / 서리·사막왕 / 그 위 · * 투기장 장비', font=fb, fill=(242, 190, 60))
    for i, (nm, fn) in enumerate(items):
        c, r = i % cols, i // cols; x0, y0 = 10 + c * GW, 44 + r * RH
        d.text((x0, y0 + H * Z // 2 - 8), nm, font=f, fill=(225, 225, 225))
        for k in range(4):
            x = x0 + 104 + k * (TW + 4)
            d.rectangle((x, y0, x + TW - 1, y0 + H * Z + 7), fill=(40, 34, 30), outline=(80, 66, 46))
            big = O.render(lambda a, fn=fn, k=k: fn(a, k), Z); sh.paste(big, (x + 4, y0 + 4), big)
    sh.save(out)
