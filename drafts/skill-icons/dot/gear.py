def art(a, cm_or_rows, look):
    rows = cm_or_rows if isinstance(cm_or_rows, list) else grid(cm_or_rows)
    if look < 1: rows = [r.replace('J', 'y') for r in rows]   # 견습 단계는 보석 없이
    sp(a, rows, LOOK[look], glow_c=GLOW[look])
def sparkle(a, look, pts):
    for (x, y) in pts[:max(0, look - 1)]:
        if a.get(x, y) == KEY: a.set(x, y, '#ffffff')
