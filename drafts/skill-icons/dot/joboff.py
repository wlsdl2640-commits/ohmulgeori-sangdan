def huntinghorn(a):   # 사냥꾼: 사냥 뿔피리 (C자로 휜 뿔 + 쇠 테 + 녹색 끈)
    cx, cy, R0 = 7.6, 7.2, 5.2; cm = {}
    for y in range(H):
        for x in range(W):
            dx, dy = x + 0.5 - cx, y + 0.5 - cy; r = math.hypot(dx, dy); ang = math.degrees(math.atan2(dy, dx)) % 360
            # 140°(왼쪽 아래) → 90°(아래) → 0° → -40°(오른쪽 위): 각을 0..1로
            t = None
            if 140 >= ang >= 0: t = (140 - ang) / 180
            elif ang >= 320: t = (140 + 360 - ang) / 180
            if t is None: continue
            w = 0.7 + 2.3 * t ** 1.6
            if abs(r - R0) <= w:
                cm[(x, y)] = 'm' if t > 0.93 else ('e' if r < R0 else 'E')
    for t in (0.38, 0.62):
        a_ = math.radians(140 - t * 180)
        for k in range(-3, 4):
            rr = R0 + k * 0.6; x, y = int(cx + math.cos(a_) * rr), int(cy + math.sin(a_) * rr)
            if (x, y) in cm: cm[(x, y)] = 'Y'
    for (x, y) in [(3, 3), (4, 2), (5, 2), (6, 1), (7, 1), (8, 1), (9, 2), (10, 2)]: cm.setdefault((x, y), 'g')
    sp(a, grid(cm), {'e': ('#f0e8d0', 7), 'E': ('#c8a070', 7), 'g': ('#4a9a3a', 8), 'Y': ('#c0901c', 6)})
