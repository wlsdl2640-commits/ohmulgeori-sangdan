def sheet(out):
    from PIL import Image, ImageDraw, ImageFont
    f = ImageFont.truetype('/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc', 14, index=2)
    fb = ImageFont.truetype('/usr/share/fonts/opentype/noto/NotoSansCJK-Bold.ttc', 17, index=2)
    Z = 6; CW, RH, LW = W * Z + 70, H * Z + 56, 120
    sh = Image.new('RGB', (LW + CW * 4 + 10, RH * len(JOB) + 50), (21, 23, 28)); d = ImageDraw.Draw(sh)
    d.text((10, 10), '2차 직업 전용 부장비 시안 · 3차 직업도 그대로 쓴다 · 오른쪽 작은 그림 = 목록 크기', font=fb, fill=(242, 190, 60))
    for r, (jb, jn, items) in enumerate(JOB):
        y = 44 + r * RH
        d.text((10, y + 50), jn, font=fb, fill=(240, 240, 240))
        for c, (cls, cn, nm, fn) in enumerate(items):
            x = LW + c * CW
            d.rectangle((x, y, x + W * Z + 8, y + H * Z + 8), fill=(40, 34, 30), outline=(90, 74, 50))
            big = O.render(fn, Z); sh.paste(big, (x + 4, y + 4), big)
            sm = O.render(fn, 2); d.rectangle((x + W * Z + 14, y + 4, x + W * Z + 14 + 36, y + 4 + 44), fill=(40, 34, 30)); sh.paste(sm, (x + W * Z + 16, y + 6), sm)
            d.text((x, y + H * Z + 12), f'{cn} · {nm}', font=f, fill=(210, 210, 210))
    sh.save(out)
