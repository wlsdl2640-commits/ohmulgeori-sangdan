"""칼자루 비교: 강타 구도에 자루만 바꿔 끼우기"""
import cell, importlib
from cell import Art, radial
w = importlib.import_module('w4')
HILT = {'g': ('#ffd84a', 6), 'G': ('#c08a1c', 6), 'h': ('#fff6c8', 1), 'r': ('#b0682a', 9), 'R': ('#7a4220', 9)}
BLADE = ['.......wmM......', '......wmM.......', '.....wmM........', '....wmM.........', '...wmM..........', '...mM...........', '..m.............']
H = {
 'H1': ['................', '................', '................', '................',
        '................', '............g...', '...........r....', '........ggR.....', '.........gg.....'],
 'H2': ['................', '................', '................', '................',
        '................', '............g...', '.......g...r....', '........g.R.....', '.........g......'],
 'H3': ['................', '................', '................', '................',
        '............gG..', '............GG..', '...........r....', '.......hggR.....', '........ggg.....'],
 'H4': ['................', '................', '................', '................',
        '.............g..', '............r...', '...........R....', '.......hg.r.....', '........ggg.....'],
}
def make(k):
    def fn():
        a = Art().bg(radial(w.DARKFIRE, 9.0, 11.0, 12.5, [0.0, 0.18, 0.36, 0.56, 0.78]))
        w.slash(a, cell.crescent2((8.5, 10.0), 7.6, (10.2, 11.4), 7.2))
        rows = H[k] + ['................'] * 0
        full = list(H[k]) + BLADE
        # 날 아래 끝: 9번째 줄부터 (날 밑동 줄은 코등이 줄과 겹치게)
        full = H[k][:9] + BLADE
        if k == 'H2': full[9] = '.......wmMg.....'; full.insert(10, '......wmM..g....'); full = full[:10] + BLADE[1:]
        a.sym(full, HILT); w.flash(a, 2, 15)
        return a, 0
    return fn
ICONS = {k: (k, 'dmg', make(k)) for k in H}
