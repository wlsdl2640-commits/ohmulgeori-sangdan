function pxGiantSprite(id) {
  const M = PXRAID[id]; if (!M) return null;
  const key = 'PR|' + id, hit = PXC.get(key + '|' + (FLASH || '') + (PX_FX ? '|fx' : '') + (PX_CHUNK ? '|c' : ''));
  if (hit) return hit;
  const rows = pxRows(M.g), W = Math.max(...rows.map(r => r.length)), H = rows.length, g = pxGrid(W + 2, H + 2);
  pxPut(g, rows, 1, 1);
  return pxBake(key, g, M.pal, Math.round((W + 2) / 2), H + 1, true);
}
