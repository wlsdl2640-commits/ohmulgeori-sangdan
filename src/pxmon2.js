Object.keys(PXM2).forEach(id => {
  const M = PXM2[id], rows = M.h.split('\n').filter(r => r.trim().length);
  const W = Math.max(...rows.map(r => r.length));
  // pxMonSprite가 격자를 (1,1)에 놓으므로 위·왼쪽에 빈 줄을 하나 더 넣어 2×2 블록이 짝수 칸에 맞게 한다
  const g = ['.'.repeat(W * 2 + 1)].concat(rows.map(r => '.' + r.padEnd(W, '.').split('').map(ch => ch + ch).join('')).flatMap(r => [r, r])).join('\n');
  PXM[id] = { g: '\n' + g + '\n', pal: M.pal || {} };
});
