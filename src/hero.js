function skillGlyph(s) {
  if (s.passive) return 'book';
  if (s.kind === 'heal') return s.tgt === 'party' ? 'healp' : 'heal';
  if (s.kind === 'buff') return s.stat === 'def' ? 'shield' : s.stat === 'atk' ? 'batk' : s.stat === 'eva' || s.stat === 'spd' ? 'wing' : 'buff';
  if (s.kind === 'taunt') return 'taunt';
  if (s.kind === 'dot') return s.fx === 'dark' ? 'curse' : s.fx === 'fire' ? 'fire' : 'poison';
  if (s.fx) return { arrow: (s.hits || 1) > 1 ? 'volley' : 'arrow', bolt: 'bolt', dark: 'dark', fire: 'fire', holy: 'holy', ice: 'ice', jump: 'heavy', wind: 'wind' }[s.fx] || 'magic';
  if (s.kind === 'mdmg') return 'magic';
  return (s.hits || 1) > 1 ? 'flurry' : s.mult >= 2.4 ? 'heavy' : 'slash';
}
const HEX_TINT = { dmg: '#4a2a22', mdmg: '#2e2246', heal: '#1e3a24', buff: '#1e2a44', dot: '#243a1e', taunt: '#4a2e18', none: '#241e1a' };
const HEX_URL = {}, HEX_W = 48;
// 육각 칸 한 장: 글리프·종류·숙련 완료 표시
function hexURL(glyph, kind, max) {
  const key = (glyph || '-') + '|' + (kind || '') + '|' + (max ? 1 : 0);
  if (HEX_URL[key]) return HEX_URL[key];
  const W = HEX_W, [c, x] = mkCanvas(W, W), cx = W / 2, cy = W / 2, r = 22;
  const span = y => { // 뾰족한 꼭짓점이 위로 간 육각형의 가로 폭
    const dy = Math.abs(y + 0.5 - cy), half = dy <= r / 2 ? r * 0.866 : r * 0.866 * (r - dy) / (r / 2);
    return half > 0 ? [Math.round(cx - half), Math.round(cx + half)] : null;
  };
  const line = (y, c0, c1, col) => { x.fillStyle = col; x.fillRect(c0, y, c1 - c0, 1); };
  for (let y = 0; y < W; y++) { const s = span(y); if (s) line(y, s[0], s[1], '#120e0c'); }
  for (let y = 2; y < W - 2; y++) {
    const s = span(y); if (!s) continue;
    const t = span(y - 2), b = span(y + 2);
    const edge = !t || !b, l = Math.max(s[0] + 2, t ? t[0] + 1 : s[0] + 2, b ? b[0] + 1 : s[0] + 2), rr = Math.min(s[1] - 2, t ? t[1] - 1 : s[1] - 2, b ? b[1] - 1 : s[1] - 2);
    line(y, s[0] + 1, s[1] - 1, glyph ? (y < cy ? '#c8a870' : '#8a6a3c') : '#4a4038');
    if (!edge && l < rr) line(y, l, rr, glyph ? (y < cy ? '#8a6a3c' : '#5a4428') : '#2a2420');
    if (!edge && l + 1 < rr - 1) line(y, l + 1, rr - 1, glyph ? HEX_TINT[kind] || HEX_TINT.none : '#141010');
  }
  if (glyph && GLYPH[glyph]) {
    const rows = frRows(GLYPH[glyph]), gx = cx - 8, gy = cy - 8;
    rows.forEach((row, yy) => { for (let i = 0; i < row.length; i++) if (row[i] !== '.' && row[i] !== ' ') { x.fillStyle = GL_PAL[row[i]] || '#ff00ff'; x.fillRect(gx + i, gy + yy, 1, 1); } });
  }
  if (max) { // 초록 체크
    const chk = ['......kk', '.....kgk', '....kggk', 'kk.kggk.', 'kgkggk..', 'kgggk...', '.kgk....', '..k.....'];
    chk.forEach((row, yy) => { for (let i = 0; i < row.length; i++) if (row[i] !== '.') { x.fillStyle = row[i] === 'k' ? '#0e2a0e' : '#5ae050'; x.fillRect(W - 12 + i, 3 + yy, 1, 1); } });
  }
  return (HEX_URL[key] = c.toDataURL());
}

