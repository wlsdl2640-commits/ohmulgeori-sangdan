const frRows = s => s.replace(/^\n+/, '').replace(/\s+$/, '').split('\n');
const FR_URL = {};
function frameURL(name) {
  if (FR_URL[name]) return FR_URL[name];
  let rows = frRows(FR_IMG[name === 'rbr' ? 'rbl' : name]);
  if (name === 'rbr') rows = rows.map(r => [...r].reverse().join(''));
  const w = rows[0].length, h = rows.length, [c, x] = mkCanvas(w, h);
  rows.forEach((r, y) => { for (let i = 0; i < w; i++) if (r[i] !== '.') { x.fillStyle = FR_PAL[r[i]]; x.fillRect(i, y, 1, 1); } });
  return (FR_URL[name] = c.toDataURL());
}
function applyFrames() {
  const st = document.documentElement.style;
  for (const n of ['parch', 'inset', 'wood', 'dark', 'stone', 'rbm', 'rbl', 'rbr']) st.setProperty('--f-' + n, `url("${frameURL(n)}")`);
}

