// 세계수 뿌리 몬스터 무기 (빌드 58): 트렌트 수호자 옹이 몽둥이 · 자작나무 지팡이 / 드라이어드 꽃 지팡이 · 씨앗 · 꽃가루 · 단풍잎
// 옹이 몽둥이 (트렌트 A 방패 나무 기사): 굵은 통나무 · 옹이 혹 · 끝이 굵다
PXU_WPN.wclub = (F, d) => { const [hx, hy] = pxsMHand(F), [dx, dy] = pxsDir(F.a || 0), px = -dy, py = dx, out = [], k = (d && d.ms) || 1, L = 5.6 * k;
  const at = (t, s, ch) => out.push([hx + dx * t + px * s, hy + dy * t + py * s, ch]);
  for (let t = -0.6; t <= L; t += 0.5) { const w = 0.5 + 0.9 * Math.max(0, t / L); for (let s = -w; s <= w + 0.01; s += 0.5) at(t, s, s < -w + 0.4 ? 'O' : 'v'); }
  for (const [t, s] of [[L * 0.45, 1.4], [L * 0.75, -1.6], [L * 0.9, 1.5]]) at(t, s, 'v');
  return out; };
PXU_FXW.wclub = 'club';
// 자작나무 지팡이 (트렌트 C 꽃 피운 수호자): 흰 자작 자루에 검은 눈 · 끝에 분홍 꽃송이
PXU_WPN.bstaff = (F, d) => { const [hx, hy] = pxsMHand(F), [dx, dy] = pxsDir(F.a || 0), px = -dy, py = dx, out = [], k = (d && d.ms) || 1, L = 7 * k;
  const at = (t, s, ch) => out.push([hx + dx * t + px * s, hy + dy * t + py * s, ch]);
  for (let t = -2; t <= L; t += 0.5) at(t, 0, Math.round(t * 2) % 5 === 0 ? 'k' : 'U');
  for (const [t, s, ch] of [[L + 0.6, 0, 'R'], [L + 1.1, -0.8, 'r'], [L + 1.1, 0.8, 'R'], [L + 1.6, 0, 'w'], [L + 0.4, 1.2, 'G'], [L + 0.2, -1.2, 'G']]) at(t, s, ch);
  return out; };
PXU_FXW.bstaff = 'staff';
// 꽃 지팡이 (드라이어드 A): 가는 초록 줄기 · 잎 둘 · 끝에 활짝 핀 분홍 꽃
PXU_WPN.fbloom = (F, d) => { const [hx, hy] = pxsMHand(F), [dx, dy] = pxsDir(F.a || 0), px = -dy, py = dx, out = [], L = 4.6;
  const at = (t, s, ch) => out.push([hx + dx * t + px * s, hy + dy * t + py * s, ch]);
  for (let t = -0.6; t <= L; t += 0.5) at(t, 0, 'g');
  at(L * 0.5, 0.9, 'G'); at(L * 0.65, -0.9, 'G');
  for (const [t, s, ch] of [[L + 0.6, 0, 'Y'], [L + 0.6, -1, 'R'], [L + 0.6, 1, 'R'], [L + 1.4, 0, 'R'], [L - 0.2, 0, 'R'], [L + 1.2, -0.9, 'r'], [L + 1.2, 0.9, 'r']]) at(t, s, ch);
  return out; };
