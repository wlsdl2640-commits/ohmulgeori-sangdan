// 꽃가루 구슬 (드라이어드 C): 손 위의 노란 꽃가루 뭉치와 흩날리는 점
PXU_WPN.fpollen = (F, d) => { const [hx, hy] = pxsMHand(F), out = [];
  for (let y = -4; y <= -1; y++) for (let x = -1; x <= 2; x++) { const r = Math.hypot(x - 0.5, y + 2.5); if (r <= 1.8) out.push([hx + x, hy + y, r < 0.8 ? 'X' : 'Y']); }
  out.push([hx - 1.6, hy - 4.6, 'Y'], [hx + 2.6, hy - 5, 'Y'], [hx + 0.6, hy - 5.8, 'X']);
  return out; };
PXU_FXW.fpollen = 'dagger';
